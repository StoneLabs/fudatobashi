  String get runFastestRanked => t('runFastestRanked');
  String get runBestRating => t('runBestRating');
  String get runExamWonText => t('runExamWonText');
  String get runExamLostText => t('runExamLostText');
  String get runFreeNoRank => t('runFreeNoRank');
  String get runXpLabel => t('runXpLabel');
  String get runXpTotal => t('runXpTotal');
  String runLevelFrom(Object a0) => f('runLevelFrom', [a0]);
  String get runNoXp => t('runNoXp');
  String get runTrainingNoRank => t('runTrainingNoRank');
  String get runPracticeNoRank => t('runPracticeNoRank');
  String get weekdayShort => t('weekdayShort');
  String runExamBeat(Object a0) => f('runExamBeat', [a0]);
  String runExamBeaten(Object a0) => f('runExamBeaten', [a0]);
}

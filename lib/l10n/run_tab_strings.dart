import '../domain/rating.dart';
import 'ranked_strings.dart';
import 'strings.dart';

/// Strings of a run page's Speed, Rating and XP tabs.
extension RunTabStrings on S {
  String runSpeedForfeit(int cards) => f(countKey('runSpeedForfeit', cards), [cards]);
  String get runThirdsTitle => t('runThirdsTitle');
  /// "Cards 4–6", or "Card 3" when the range is one card.
  String runCardsRange(int from, int to) => from == to ? f('runCardAt', [from]) : f('runCardsRange', [from, to]);
  String get runSlowestThird => t('runSlowestThird');
  String get runFastestThird => t('runFastestThird');
  String get runSlowStart => t('runSlowStart');
  String runVsRun(Object a0) => f('runVsRun', [a0]);
  String runMissMark(Object a0) => f('runMissMark', [a0]);
  String get runSwipeTimesOnly => t('runSwipeTimesOnly');
  String runSwipeTimesPenalty(Object a0) => f('runSwipeTimesPenalty', [a0]);
  String runPaceTitle(Object a0) => f('runPaceTitle', [a0]);
  String runAverageNote(Object a0) => f('runAverageNote', [a0]);
  String get runStretchTitle => t('runStretchTitle');
  String runFastestRow(Object a0) => f('runFastestRow', [a0]);
  String runStretchLine(Object a0, Object a1, Object a2) => f('runStretchLine', [a0, a1, a2]);
  String runUnderGoalRow(Object a0) => f('runUnderGoalRow', [a0]);
  String runNoMissRange(int from, int to) => from == to ? f('runNoMissAt', [from]) : f('runNoMissRange', [from, to]);
  String get runNone => t('runNone');
  String get runNoneThisRun => t('runNoneThisRun');
  String get runPaceFast => t('runPaceFast');
  String get runPaceUnderGoal => t('runPaceUnderGoal');
  String get runPaceSlow => t('runPaceSlow');
  String runPaceFastestRow(Object a0) => f('runPaceFastestRow', [a0]);
  String get runUpright => t('runUpright');
  String get runUpsideDownSide => t('runUpsideDownSide');
  String runSideLine(int cards, int misses) =>
      f('runSideLine', [cardsCount(cards), f(countKey('runSideMisses', misses), [misses])]);
  String runUpsideCost(Object a0) => f('runUpsideCost', [a0]);
  String runUpsideGain(Object a0) => f('runUpsideGain', [a0]);
  String get runKimarijiTitle => t('runKimarijiTitle');
  String get runKimarijiNote => t('runKimarijiNote');
  String runKimarijiLength(Object a0) => f('runKimarijiLength', [a0]);
  String get runUsualTitle => t('runUsualTitle');
  String runUsualFor(Object a0) => f('runUsualFor', [a0]);
  String get runSwipesOnly => t('runSwipesOnly');
  String runFasterOn(Object a0, Object a1) => f('runFasterOn', [a0, a1]);
  String runOverallFaster(Object a0) => f('runOverallFaster', [a0]);
  String runOverallSlower(Object a0) => f('runOverallSlower', [a0]);
  String get runMostGained => t('runMostGained');
  String get runMostLost => t('runMostLost');
  String get runNoUsual => t('runNoUsual');
  String get runNewRating => t('runNewRating');
  String get runPlacementShout => t('runPlacementShout');
  String runPlacementText(Object a0, Object a1) => f('runPlacementText', [a0, a1]);
  String runClassGap(Object a0, RankBand next, Object a2) => f('runClassGap', [a0, className(next), a2]);
  String runPlacementForfeitText(Object a0) => f('runPlacementForfeitText', [a0]);
  String runForfeitText(Object a0) => f('runForfeitText', [a0]);
  String get runRankedTitle => t('runRankedTitle');
  String runSoFar(Object a0) => f('runSoFar', [a0]);
  String get runColRun => t('runColRun');
  String get runColScored => t('runColScored');
